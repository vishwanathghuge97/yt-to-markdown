import { getAccessToken } from './firebase';

export interface DriveUploadResult {
  id: string;
  name: string;
  webViewLink?: string;
  folderId?: string;
  createdTime?: string;
}

const FOLDER_NAME = 'YouTube Summaries & Notes';

/**
 * Ensures or creates a dedicated folder in Google Drive for app exports
 */
export async function getOrCreateExportFolder(): Promise<string> {
  const token = await getAccessToken();
  if (!token) throw new Error('Not authenticated with Google');

  // Search for existing folder
  const query = `name = '${FOLDER_NAME}' and mimeType = 'application/vnd.google-apps.folder' and trashed = false`;
  const searchUrl = `https://www.googleapis.com/drive/v3/files?q=${encodeURIComponent(query)}&fields=files(id,name)`;

  const searchRes = await fetch(searchUrl, {
    headers: { Authorization: `Bearer ${token}` },
  });

  if (!searchRes.ok) {
    const errorText = await searchRes.text();
    throw new Error(`Google Drive search failed (${searchRes.status}): ${errorText}`);
  }

  const searchData = await searchRes.json();
  if (searchData.files && searchData.files.length > 0) {
    return searchData.files[0].id;
  }

  // Create folder
  const createRes = await fetch('https://www.googleapis.com/drive/v3/files', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      name: FOLDER_NAME,
      mimeType: 'application/vnd.google-apps.folder',
      description: 'Video notes and markdown transcripts exported from yt-to-markdown',
    }),
  });

  if (!createRes.ok) {
    const errorText = await createRes.text();
    throw new Error(`Failed to create Google Drive folder: ${errorText}`);
  }

  const folderData = await createRes.json();
  return folderData.id;
}

/**
 * Saves a markdown summary file into the Google Drive folder.
 */
export async function saveMarkdownToDrive(
  fileName: string,
  content: string,
  description?: string
): Promise<DriveUploadResult> {
  const token = await getAccessToken();
  if (!token) throw new Error('User is not authenticated with Google Drive');

  // Ensure destination folder
  const folderId = await getOrCreateExportFolder();

  const metadata = {
    name: fileName.endsWith('.md') ? fileName : `${fileName}.md`,
    mimeType: 'text/markdown',
    parents: [folderId],
    description: description || 'Generated by yt-to-markdown Video Analyzer',
  };

  const boundary = '-------314159265358979323846';
  const delimiter = `\r\n--${boundary}\r\n`;
  const closeDelimiter = `\r\n--${boundary}--`;

  const multipartRequestBody =
    delimiter +
    'Content-Type: application/json; charset=UTF-8\r\n\r\n' +
    JSON.stringify(metadata) +
    delimiter +
    'Content-Type: text/markdown; charset=UTF-8\r\n\r\n' +
    content +
    closeDelimiter;

  const uploadRes = await fetch(
    'https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,name,webViewLink,createdTime',
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': `multipart/related; boundary=${boundary}`,
      },
      body: multipartRequestBody,
    }
  );

  if (!uploadRes.ok) {
    const errorText = await uploadRes.text();
    throw new Error(`Failed to upload file to Google Drive: ${errorText}`);
  }

  const result = await uploadRes.json();
  return {
    id: result.id,
    name: result.name,
    webViewLink: result.webViewLink,
    folderId,
    createdTime: result.createdTime,
  };
}

/**
 * Fetches recent files exported to the yt-to-markdown notes folder
 */
export async function listRecentDriveExports(): Promise<DriveUploadResult[]> {
  const token = await getAccessToken();
  if (!token) return [];

  try {
    const folderId = await getOrCreateExportFolder();
    const query = `'${folderId}' in parents and trashed = false`;
    const url = `https://www.googleapis.com/drive/v3/files?q=${encodeURIComponent(
      query
    )}&orderBy=createdTime desc&pageSize=10&fields=files(id,name,webViewLink,createdTime)`;

    const res = await fetch(url, {
      headers: { Authorization: `Bearer ${token}` },
    });

    if (!res.ok) return [];
    const data = await res.json();
    return data.files || [];
  } catch (err) {
    console.error('Failed to list Drive files:', err);
    return [];
  }
}
