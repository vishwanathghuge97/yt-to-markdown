import { getAccessToken, googleSignIn } from './firebase';
import { updateCreationDriveInfo } from './creationStorage';

export interface DriveUploadResult {
  id: string;
  name: string;
  webViewLink?: string;
  folderId?: string;
  createdTime?: string;
  size?: string;
}

const FOLDER_NAME = 'YouTube Summaries & Notes';

async function getValidToken(): Promise<string> {
  let token = await getAccessToken();
  if (!token) {
    const res = await googleSignIn();
    token = res?.accessToken || null;
  }
  if (!token) {
    throw new Error('Not authenticated with Google Drive. Please click Connect Drive.');
  }
  return token;
}

/**
 * Ensures or creates a dedicated folder in Google Drive for app exports
 */
export async function getOrCreateExportFolder(): Promise<string> {
  let token = await getValidToken();

  // Search for existing folder
  const query = `name = '${FOLDER_NAME}' and mimeType = 'application/vnd.google-apps.folder' and trashed = false`;
  const searchUrl = `https://www.googleapis.com/drive/v3/files?q=${encodeURIComponent(query)}&fields=files(id,name)`;

  let searchRes = await fetch(searchUrl, {
    headers: { Authorization: `Bearer ${token}` },
  });

  if (searchRes.status === 401) {
    const reauth = await googleSignIn();
    if (reauth?.accessToken) {
      token = reauth.accessToken;
      searchRes = await fetch(searchUrl, {
        headers: { Authorization: `Bearer ${token}` },
      });
    }
  }

  if (!searchRes.ok) {
    const errorText = await searchRes.text();
    throw new Error(`Google Drive search failed (${searchRes.status}): ${errorText}`);
  }

  const searchData = await searchRes.json();
  if (searchData.files && searchData.files.length > 0) {
    return searchData.files[0].id;
  }

  // Create folder
  const createRes = await fetch('https://www.googleapis.com/drive/v3/files', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      name: FOLDER_NAME,
      mimeType: 'application/vnd.google-apps.folder',
      description: 'Video notes and markdown transcripts exported from yt-to-markdown',
    }),
  });

  if (!createRes.ok) {
    const errorText = await createRes.text();
    throw new Error(`Failed to create Google Drive folder: ${errorText}`);
  }

  const folderData = await createRes.json();
  return folderData.id;
}

/**
 * Saves a markdown summary file into the Google Drive folder.
 */
export async function saveMarkdownToDrive(
  fileName: string,
  content: string,
  description?: string
): Promise<DriveUploadResult> {
  let token = await getValidToken();

  // Ensure destination folder
  const folderId = await getOrCreateExportFolder();

  const metadata = {
    name: fileName.endsWith('.md') ? fileName : `${fileName}.md`,
    mimeType: 'text/markdown',
    parents: [folderId],
    description: description || 'Generated by yt-to-markdown Video Analyzer',
  };

  const boundary = '-------314159265358979323846';
  const delimiter = `\r\n--${boundary}\r\n`;
  const closeDelimiter = `\r\n--${boundary}--`;

  const multipartRequestBody =
    delimiter +
    'Content-Type: application/json; charset=UTF-8\r\n\r\n' +
    JSON.stringify(metadata) +
    delimiter +
    'Content-Type: text/markdown; charset=UTF-8\r\n\r\n' +
    content +
    closeDelimiter;

  let uploadRes = await fetch(
    'https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,name,webViewLink,createdTime',
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': `multipart/related; boundary=${boundary}`,
      },
      body: multipartRequestBody,
    }
  );

  if (uploadRes.status === 401) {
    const reauth = await googleSignIn();
    if (reauth?.accessToken) {
      token = reauth.accessToken;
      uploadRes = await fetch(
        'https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,name,webViewLink,createdTime',
        {
          method: 'POST',
          headers: {
            Authorization: `Bearer ${token}`,
            'Content-Type': `multipart/related; boundary=${boundary}`,
          },
          body: multipartRequestBody,
        }
      );
    }
  }

  if (!uploadRes.ok) {
    const errorText = await uploadRes.text();
    throw new Error(`Failed to upload file to Google Drive: ${errorText}`);
  }

  const result = await uploadRes.json();
  const exportResult: DriveUploadResult = {
    id: result.id,
    name: result.name,
    webViewLink: result.webViewLink,
    folderId,
    createdTime: result.createdTime,
  };

  try {
    updateCreationDriveInfo(fileName, result.id, result.webViewLink);
  } catch (e) {
    console.warn('Could not update creation history:', e);
  }

  return exportResult;
}

/**
 * Fetches recent files exported to the yt-to-markdown notes folder or Drive
 */
export async function listRecentDriveExports(): Promise<DriveUploadResult[]> {
  let token = await getAccessToken();
  if (!token) {
    const err: any = new Error('Google Drive authorization required.');
    err.code = 'AUTH_REQUIRED';
    throw err;
  }

  let folderId: string | null = null;
  try {
    folderId = await getOrCreateExportFolder();
  } catch (folderErr) {
    console.warn('Folder resolution notice:', folderErr);
  }

  // Broad query ensures notes created across sessions, folders, or root are discovered
  const query = folderId
    ? `trashed = false and ('${folderId}' in parents or mimeType = 'text/markdown' or name contains '.md')`
    : `trashed = false and (mimeType = 'text/markdown' or name contains '.md')`;

  const url = `https://www.googleapis.com/drive/v3/files?q=${encodeURIComponent(
    query
  )}&orderBy=createdTime desc&pageSize=50&fields=files(id,name,webViewLink,createdTime,size,parents)`;

  let res = await fetch(url, {
    headers: { Authorization: `Bearer ${token}` },
  });

  if (res.status === 401) {
    const err: any = new Error('Google Drive session expired.');
    err.code = 'AUTH_REQUIRED';
    throw err;
  }

  if (!res.ok) {
    const errorText = await res.text();
    throw new Error(`Google Drive sync notice (${res.status}): ${errorText}`);
  }

  const data = await res.json();
  return data.files || [];
}


/**
 * Reads the raw markdown content of a file from Google Drive
 */
export async function fetchDriveFileContent(fileId: string): Promise<string> {
  let token = await getValidToken();
  const url = `https://www.googleapis.com/drive/v3/files/${encodeURIComponent(fileId)}?alt=media`;

  let res = await fetch(url, {
    headers: { Authorization: `Bearer ${token}` },
  });

  if (res.status === 401) {
    const reauth = await googleSignIn();
    if (reauth?.accessToken) {
      token = reauth.accessToken;
      res = await fetch(url, {
        headers: { Authorization: `Bearer ${token}` },
      });
    }
  }

  if (!res.ok) {
    throw new Error(`Failed to read file from Google Drive (${res.status})`);
  }

  return await res.text();
}

/**
 * Deletes a file from the user's Google Drive folder
 */
export async function deleteDriveFile(fileId: string): Promise<boolean> {
  let token = await getValidToken();
  const url = `https://www.googleapis.com/drive/v3/files/${encodeURIComponent(fileId)}`;

  let res = await fetch(url, {
    method: 'DELETE',
    headers: { Authorization: `Bearer ${token}` },
  });

  if (res.status === 401) {
    const reauth = await googleSignIn();
    if (reauth?.accessToken) {
      token = reauth.accessToken;
      res = await fetch(url, {
        method: 'DELETE',
        headers: { Authorization: `Bearer ${token}` },
      });
    }
  }

  if (!res.ok && res.status !== 204 && res.status !== 404) {
    throw new Error(`Failed to delete file from Google Drive (${res.status})`);
  }

  return true;
}
